import "server-only";

import { and, asc, eq, inArray } from "drizzle-orm";

import { db } from "@/db/client";
import { adjustments, commodities, grades, lots, warehouses } from "@/db/schema";
import type { OrgContext } from "@/lib/authz/context";

/**
 * Small org-scoped label lookups for the warehouse pages (ids → names).
 * Read-only; no prices. Rows from the P2-B services carry bare ids
 * (transfer lines, count lines, adjustments), so pages resolve labels here.
 */

export type WarehouseLabel = { id: string; name: string; active: boolean };

/**
 * Every warehouse in the org (names only). Transfer destinations and labels
 * may sit outside a keeper's restriction, so this deliberately ignores
 * ctx.restrictions.warehouseIds — it exposes nothing beyond names.
 */
export async function orgWarehouseLabels(ctx: OrgContext): Promise<WarehouseLabel[]> {
  return db
    .select({ id: warehouses.id, name: warehouses.name, active: warehouses.active })
    .from(warehouses)
    .where(eq(warehouses.organisationId, ctx.orgId))
    .orderBy(asc(warehouses.name));
}

export type LotLabel = { id: string; lotNumber: string; commodityName: string; gradeName: string };

export async function lotLabels(ctx: OrgContext, ids: string[]): Promise<Map<string, LotLabel>> {
  const unique = [...new Set(ids)];
  if (unique.length === 0) return new Map();
  const rows = await db
    .select({
      id: lots.id,
      lotNumber: lots.lotNumber,
      commodityName: commodities.name,
      gradeName: grades.name,
    })
    .from(lots)
    .innerJoin(commodities, eq(commodities.id, lots.commodityId))
    .innerJoin(grades, eq(grades.id, lots.gradeId))
    .where(and(eq(lots.organisationId, ctx.orgId), inArray(lots.id, unique)));
  return new Map(rows.map((r) => [r.id, r]));
}

/** Adjustments generated by posting a count. */
export async function adjustmentsForCount(ctx: OrgContext, countId: string) {
  return db
    .select({
      id: adjustments.id,
      adjustmentNumber: adjustments.adjustmentNumber,
      lotId: adjustments.lotId,
      kg: adjustments.kg,
      status: adjustments.status,
    })
    .from(adjustments)
    .where(and(eq(adjustments.organisationId, ctx.orgId), eq(adjustments.sourceCountId, countId)))
    .orderBy(asc(adjustments.adjustmentNumber));
}
