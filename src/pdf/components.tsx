// Statement body (shared by supplier + customer statements)

export type StatementComputed<K extends string> = StatementRow<K> & { balanceKobo: number };

/** Date-orders rows (stable) and computes the running balance. */
export function computeStatement<K extends string>(
  rows: StatementRow<K>[],
  openingBalanceKobo = 0,
): { rows: StatementComputed<K>[]; closingBalanceKobo: number } {
  const ordered = rows
    .map((r, i) => ({ r, i, key: lagosSortKey(r.date) }))
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : a.i - b.i))
    .map((x) => x.r);
  let balance = openingBalanceKobo;
  const out = ordered.map((r) => {
    balance += r.amountKobo;
    return { ...r, balanceKobo: balance };
  });
  return { rows: out, closingBalanceKobo: balance };
}

export function StatementTable<K extends string>(props: {
  rows: StatementRow<K>[];
  openingBalanceKobo?: number;
  kindLabels: Record<K, string>;
  /** Formats a running/opening balance for display (sign → DR/CR). */
  balanceLabel: (kobo: number) => string;
  /** Sentence describing who owes whom at close. */
  closingLabel: (kobo: number) => string;
}) {
  const { View, Text } = rp();
  const opening = props.openingBalanceKobo ?? 0;
  const { rows, closingBalanceKobo } = computeStatement(props.rows, opening);
  type Row = StatementComputed<K> | { opening: true };
  const all: Row[] = [{ opening: true }, ...rows];
  const columns: Column<Row>[] = [
    { header: "Date", width: 1.2, cell: (r) => ("opening" in r ? "" : pdfDate(r.date)) },
    {
      header: "Details",
      width: 2.8,
      cell: (r) =>
        "opening" in r
          ? "Opening balance"
          : `${props.kindLabels[r.kind] ?? r.kind} ${r.reference}${r.description ? ` - ${r.description}` : ""}`,
    },
    {
      header: "Debit (+)",
      width: 1.5,
      align: "right",
      cell: (r) => ("opening" in r || r.amountKobo <= 0 ? "" : pdfNaira(r.amountKobo)),
    },
    {
      header: "Credit (-)",
      width: 1.5,
      align: "right",
      cell: (r) => ("opening" in r || r.amountKobo >= 0 ? "" : pdfNaira(-r.amountKobo)),
    },
    {
      header: "Balance",
      width: 1.7,
      align: "right",
      cell: (r) => props.balanceLabel("opening" in r ? opening : r.balanceKobo),
    },
  ];
  return (
    <View>
      <Table columns={columns} rows={all} />
      <Totals
        lines={[
          { label: "Opening balance", value: props.balanceLabel(opening) },
          { label: "Closing balance", value: props.balanceLabel(closingBalanceKobo), strong: true },
        ]}
      />
      <Text style={[styles.note, styles.bold]}>{props.closingLabel(closingBalanceKobo)}</Text>
    </View>
  );
}
